/**
 * Bundle the browser half into client/client.js.
 *
 * The Host loads a client plugin as text: one lazy factory on
 * window.__ModuleLoader__, no module syntax, no dependency besides react.
 * So this script concatenates the sources under src/client in dependency
 * order, strips their single-line imports and leading export keywords, and
 * wraps the result in that factory. The same pass refuses to emit a bundle
 * that is missing the factory shape, still contains module syntax, reaches for
 * another package, uses console, or does not parse.
 *
 * Usage:
 *   node scripts/build-ui.mjs           write client/client.js
 *   node scripts/build-ui.mjs --check   fail when client/client.js is stale
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const OUTPUT = 'client/client.js';
const PLUGIN_ID = 'dsh-aihub';
const SOURCES = ['src/client/controller.mjs', 'src/client/view.mjs', 'src/client/index.mjs'];

const IMPORT_LINE = /^import \{[^\n]*\} from '(?:\.\/(?:controller|view))\.mjs';\r?\n/gm;
const EXPORT_KEYWORD = /^export (?=(?:const|function|let|class) )/gm;
const ENTRY_POINTS = ['createClientPlugin', 'createAihubSection', 'createAihubController', 'AIHUB_CSS', 'EN', 'ZH'];

function bodyOf(source, text) {
  const body = text.replace(IMPORT_LINE, '').replace(EXPORT_KEYWORD, '').trim();
  const leftover = body.match(/^\s*(?:import|export)\b.*$/m);
  if (leftover) throw new Error(source + ': module syntax is only supported as a single-line named import or a leading export keyword, found: ' + leftover[0].trim());
  return body;
}

function compose(sections) {
  const head = [
    '// Generated by node scripts/build-ui.mjs. Edit the sources under src/client instead.',
    "window.__ModuleLoader__.load({ id: '" + PLUGIN_ID + "', factory: (require) => {",
    "  'use strict';",
  ].join('\n');
  const tail = ["  return createClientPlugin(require('react'));", '} });', ''].join('\n');
  const body = sections.map(section => '// ' + section.source + '\n' + section.body).join('\n\n');
  return head + '\n' + body + '\n' + tail;
}

function checkBundle(bundle) {
  const problems = [];
  const expect = (condition, message) => {
    if (!condition) problems.push(message);
  };
  const header = "window.__ModuleLoader__.load({ id: '" + PLUGIN_ID + "', factory: (require) => {";
  const loads = bundle.match(/__ModuleLoader__\.load\(/g) || [];
  expect(loads.length === 1, 'expected one __ModuleLoader__.load call, found ' + loads.length);
  expect(bundle.indexOf(header) >= 0, 'the lazy factory header is missing');
  expect(bundle.trimEnd().endsWith("return createClientPlugin(require('react'));\n} });"), 'the factory tail is missing');
  expect(!/^\s*(?:import|export)\b/m.test(bundle), 'module syntax leaked into the bundle');
  const requires = bundle.match(/\brequire\(([^)]*)\)/g) || [];
  for (const call of requires) expect(call === "require('react')", 'unexpected external dependency: ' + call);
  expect(!/\bconsole\./.test(bundle), 'console usage is not allowed in the client bundle');
  expect(!/\bdebugger\b/.test(bundle), 'debugger statement found in the bundle');
  expect(bundle.length > 20000, 'bundle looks truncated at ' + bundle.length + ' chars');
  for (const name of ENTRY_POINTS) {
    expect(new RegExp('\\b(?:const|function) ' + name + '\\b').test(bundle), 'definition for ' + name + ' is missing');
  }
  try {
    new Function(bundle);
  } catch (error) {
    problems.push('bundle does not parse: ' + error.message);
  }
  if (problems.length > 0) throw new Error('client bundle self-check failed:\n- ' + problems.join('\n- '));
  return {
    bytes: Buffer.byteLength(bundle, 'utf8'),
    gzip: gzipSync(Buffer.from(bundle, 'utf8')).length,
    lines: bundle.split('\n').length,
    requires: requires.length,
  };
}

const sections = [];
for (const source of SOURCES) {
  const text = (await readFile(path.join(root, source), 'utf8')).replace(/\r\n/g, '\n');
  sections.push({ source, body: bodyOf(source, text) });
}

const bundle = compose(sections);
const stats = checkBundle(bundle);
const target = path.join(root, OUTPUT);
const check = process.argv.includes('--check');
const summary = stats.bytes + ' bytes, ' + stats.lines + ' lines, ' + sections.length + ' sources, gzip ' + stats.gzip + ' bytes';

if (check) {
  let current = '';
  try {
    current = await readFile(target, 'utf8');
  } catch (error) {
    console.error(OUTPUT + ' is missing; run node scripts/build-ui.mjs first');
    process.exitCode = 1;
    process.exit();
  }
  if (current !== bundle) {
    console.error(OUTPUT + ' is stale; run node scripts/build-ui.mjs');
    process.exitCode = 1;
    process.exit();
  }
  console.log(OUTPUT + ' is up to date (' + summary + '); self-check passed');
} else {
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, bundle, 'utf8');
  console.log('wrote ' + OUTPUT + ' (' + summary + ')');
  console.log('self-check passed: one lazy factory, react is the only require, no console, parses as a script');
}
